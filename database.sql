-- Schema do Personal Home Server Drive (Opção A: pastas e arquivos reais no disco, sem criptografia da aplicação)
-- Migração caso o banco antigo ainda tenha dek_salt / wrapped_dek:
--   ALTER TABLE users DROP COLUMN IF EXISTS dek_salt;
--   ALTER TABLE users DROP COLUMN IF EXISTS wrapped_dek;

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS users_nome_lower_idx ON users (lower(nome));

CREATE TABLE IF NOT EXISTS folders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users (id),
    parent_id INTEGER REFERENCES folders (id),
    nome TEXT NOT NULL,
    trashed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users (id),
    folder_id INTEGER REFERENCES folders (id),
    nome TEXT NOT NULL,
    mime TEXT,
    tamanho_bytes BIGINT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    trashed_at TIMESTAMPTZ
);
