use std::time::Duration;

use sqlx::PgPool;

fn env(key: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| panic!("{key} não definida nas variáveis de ambiente"))
}

pub async fn postgres_connection() -> Result<PgPool, sqlx::Error> {
    let user = env("DATABASE_USER");
    let password = env("DATABASE_PASSWORD");
    let host = env("DATABASE_HOST");
    let port = env("DATABASE_PORT");
    let name = env("DATABASE_NAME");

    let database_url = format!("postgres://{user}:{password}@{host}:{port}/{name}");

    let mut last_err = None;
    for attempt in 1..=20 {
        match PgPool::connect(&database_url).await {
            Ok(pool) => return Ok(pool),
            Err(e) => {
                eprintln!("Aguardando PostgreSQL ({attempt}/20): {e}");
                last_err = Some(e);
                tokio::time::sleep(Duration::from_secs(1)).await;
            }
        }
    }
    Err(last_err.expect("erro de conexão com PostgreSQL"))
}

/// Garante o schema e remove colunas legadas de criptografia caso o banco já existisse.
pub async fn ensure_schema(pool: &PgPool) -> Result<(), sqlx::Error> {
    let statements = [
        "CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome VARCHAR(50) NOT NULL UNIQUE,
            password_hash TEXT NOT NULL
        )",
        "ALTER TABLE users DROP COLUMN IF EXISTS dek_salt",
        "ALTER TABLE users DROP COLUMN IF EXISTS wrapped_dek",
        "CREATE UNIQUE INDEX IF NOT EXISTS users_nome_lower_idx ON users (lower(nome))",
        "CREATE TABLE IF NOT EXISTS folders (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_id INTEGER NOT NULL REFERENCES users (id),
            parent_id INTEGER REFERENCES folders (id),
            nome TEXT NOT NULL,
            trashed_at TIMESTAMPTZ
        )",
        "CREATE TABLE IF NOT EXISTS files (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_id INTEGER NOT NULL REFERENCES users (id),
            folder_id INTEGER REFERENCES folders (id),
            nome TEXT NOT NULL,
            mime TEXT,
            tamanho_bytes BIGINT NOT NULL,
            storage_key TEXT NOT NULL UNIQUE,
            trashed_at TIMESTAMPTZ
        )",
    ];

    for sql in statements {
        sqlx::query(sql).execute(pool).await?;
    }
    Ok(())
}
