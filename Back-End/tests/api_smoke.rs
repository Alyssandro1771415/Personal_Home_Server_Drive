//! Sobe a API contra um Postgres descartável.
//!
//! Cobre o caso que quebrou o deploy: banco antigo sem datas, migração no
//! boot e respostas HTTP com `created_at` / `updated_at`.
//!
//! Só roda com `REQUIRE_DB=1` para não apagar um banco de desenvolvimento.
//! O CI chama: `cargo test --test api_smoke -- --ignored`

use std::net::SocketAddr;
use std::time::Duration;

use chrono::Duration as ChronoDuration;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};

use drive::adapters::db::postgres_connection::{self, postgres_connection};
use drive::adapters::db::postgres_files::PostgresFiles;
use drive::adapters::db::postgres_folders::PostgresFolders;
use drive::adapters::db::postgres_users::PostgresUsers;
use drive::adapters::fs::FsStore;
use drive::adapters::http::router;
use drive::adapters::http::state::AppState;

const LEGACY_SCHEMA: &str = "
DROP TABLE IF EXISTS files, folders, users CASCADE;
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL
);
CREATE TABLE folders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users (id),
    parent_id INTEGER REFERENCES folders (id),
    nome TEXT NOT NULL,
    trashed_at TIMESTAMPTZ
);
CREATE TABLE files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users (id),
    folder_id INTEGER REFERENCES folders (id),
    nome TEXT NOT NULL,
    mime TEXT,
    tamanho_bytes BIGINT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    trashed_at TIMESTAMPTZ
);
";

#[tokio::test]
#[ignore = "precisa de Postgres descartável e REQUIRE_DB=1"]
async fn legacy_database_migrates_and_serves_files() {
    assert_eq!(
        std::env::var("REQUIRE_DB").ok().as_deref(),
        Some("1"),
        "recusou apagar o banco sem REQUIRE_DB=1"
    );

    let pool = postgres_connection().await.expect("conexão com Postgres");

    sqlx::raw_sql(LEGACY_SCHEMA)
        .execute(&pool)
        .await
        .expect("schema legado");

    let owner_id: i32 = sqlx::query_scalar(
        "INSERT INTO users (nome, password_hash) VALUES ('legado', 'x') RETURNING id",
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    let folder_id: i32 = sqlx::query_scalar(
        "INSERT INTO folders (owner_id, nome) VALUES ($1, 'Velha') RETURNING id",
    )
    .bind(owner_id)
    .fetch_one(&pool)
    .await
    .unwrap();
    sqlx::query(
        "INSERT INTO files (owner_id, folder_id, nome, mime, tamanho_bytes, storage_key)
         VALUES ($1, $2, 'legado.txt', 'text/plain', 4, 'legado/legado.txt')",
    )
    .bind(owner_id)
    .bind(folder_id)
    .execute(&pool)
    .await
    .unwrap();

    postgres_connection::ensure_schema(&pool)
        .await
        .expect("migração");
    postgres_connection::ensure_schema(&pool)
        .await
        .expect("migração repetida");

    let (created_at, updated_at): (chrono::DateTime<chrono::Utc>, chrono::DateTime<chrono::Utc>) =
        sqlx::query_as("SELECT created_at, updated_at FROM files WHERE nome = 'legado.txt'")
            .fetch_one(&pool)
            .await
            .expect("arquivo legado deve ganhar datas");
    assert!(created_at <= updated_at);

    let storage = std::env::temp_dir().join(format!("drive-smoke-{}", uuid::Uuid::new_v4()));
    tokio::fs::create_dir_all(&storage).await.unwrap();
    let state = AppState {
        users: PostgresUsers::new(pool.clone()),
        files: PostgresFiles::new(pool.clone()),
        folders: PostgresFolders::new(pool),
        store: FsStore::new(&storage),
        sessions: Default::default(),
        trash_ttl: ChronoDuration::days(30),
    };
    let app = router(state);
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    tokio::spawn(async move {
        axum::serve(listener, app).await.unwrap();
    });

    let (status, body) = call(addr, "GET", "/health", &[], &[]).await;
    assert_eq!(status, 200, "{body}");
    assert!(body.contains("OK"));

    let nome = format!(
        "ci{}",
        &uuid::Uuid::new_v4().to_string().replace('-', "")[..12]
    );
    let register = format!(r#"{{"nome":"{nome}","password":"senha1234"}}"#);
    let (status, body) = call(
        addr,
        "POST",
        "/users",
        &[("Content-Type", "application/json")],
        register.as_bytes(),
    )
    .await;
    assert_eq!(status, 201, "{body}");

    let login = format!(r#"{{"nome":"{nome}","password":"senha1234"}}"#);
    let (status, body) = call(
        addr,
        "POST",
        "/login",
        &[("Content-Type", "application/json")],
        login.as_bytes(),
    )
    .await;
    assert_eq!(status, 200, "{body}");
    let token = json_string(&body, "token");

    let auth = format!("Bearer {token}");
    let folder = r#"{"nome":"Fotos","parent_id":null}"#;
    let (status, body) = call(
        addr,
        "POST",
        "/folders",
        &[
            ("Content-Type", "application/json"),
            ("Authorization", &auth),
        ],
        folder.as_bytes(),
    )
    .await;
    assert_eq!(status, 201, "{body}");
    assert!(body.contains("created_at"), "{body}");
    assert!(body.contains("updated_at"), "{body}");

    let boundary = "drivebound";
    let file_body = format!(
        "--{boundary}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"nota.txt\"\r\nContent-Type: text/plain\r\n\r\nola\r\n--{boundary}--\r\n"
    );
    let (status, body) = call(
        addr,
        "POST",
        "/files",
        &[
            (
                "Content-Type",
                &format!("multipart/form-data; boundary={boundary}"),
            ),
            ("Authorization", &auth),
        ],
        file_body.as_bytes(),
    )
    .await;
    assert_eq!(status, 201, "{body}");
    assert!(body.contains("\"nome\":\"nota.txt\""), "{body}");
    assert!(body.contains("created_at"), "{body}");
    assert!(body.contains("updated_at"), "{body}");

    let (status, body) = call(addr, "GET", "/files", &[("Authorization", &auth)], &[]).await;
    assert_eq!(status, 200, "{body}");
    assert!(body.contains("nota.txt"), "{body}");
    assert!(body.contains("created_at"), "{body}");

    let _ = tokio::fs::remove_dir_all(&storage).await;
}

async fn call(
    addr: SocketAddr,
    method: &str,
    path: &str,
    headers: &[(&str, &str)],
    body: &[u8],
) -> (u16, String) {
    let raw = tokio::time::timeout(Duration::from_secs(20), async {
        let mut request = format!(
            "{method} {path} HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\nContent-Length: {}\r\n",
            body.len()
        );
        for (name, value) in headers {
            request.push_str(name);
            request.push_str(": ");
            request.push_str(value);
            request.push_str("\r\n");
        }
        request.push_str("\r\n");
        let mut bytes = request.into_bytes();
        bytes.extend_from_slice(body);

        let mut stream = TcpStream::connect(addr).await.unwrap();
        stream.write_all(&bytes).await.unwrap();
        let mut buf = Vec::new();
        stream.read_to_end(&mut buf).await.unwrap();
        String::from_utf8(buf).unwrap()
    })
    .await
    .unwrap_or_else(|_| panic!("timeout em {method} {path}"));

    let status = raw
        .lines()
        .next()
        .and_then(|line| line.split_whitespace().nth(1))
        .and_then(|code| code.parse().ok())
        .unwrap_or_else(|| panic!("status ausente em {raw}"));
    let payload = raw.split_once("\r\n\r\n").map(|(_, b)| b).unwrap_or("");
    (status, payload.to_string())
}

fn json_string(body: &str, field: &str) -> String {
    let key = format!("\"{field}\":\"");
    let start = body
        .find(&key)
        .unwrap_or_else(|| panic!("campo {field} ausente em {body}"));
    let rest = &body[start + key.len()..];
    let end = rest.find('"').expect("string JSON sem fim");
    rest[..end].to_string()
}
